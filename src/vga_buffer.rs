pub struct FramebufferConsole {
    pub addr: *mut u32,
    pub width: usize,
    pub height: usize,
    pub pitch: usize,
    cursor_x: usize,
    cursor_y: usize,
}

unsafe impl Send for FramebufferConsole {}

impl FramebufferConsole {
    pub const fn new() -> Self {
        FramebufferConsole {
            addr: core::ptr::null_mut(),
            width: 0,
            height: 0,
            pitch: 0,
            cursor_x: 20,
            cursor_y: 20,
        }
    }

    pub fn init(&mut self, addr: *mut u32, width: usize, height: usize, pitch: usize) {
        self.addr = addr;
        self.width = width;
        self.height = height;
        self.pitch = pitch / 4;
        self.nettoyer_ecran();
    }

    fn max_y(&self) -> usize {
        if self.height > (CHAR_HEIGHT * 2) {
            self.height - CHAR_HEIGHT
        } else {
            self.height
        }
    }

    pub fn ecrire_chaine(&mut self, s: &str) {
        if self.addr.is_null() { return; }

        let max_y = self.max_y();

        for c in s.chars() {
            match c {
                '\n' => {
                    self.cursor_x = 20;
                    self.cursor_y += LINE_HEIGHT;
                    if self.cursor_y >= max_y {
                        self.scroll_up();
                    }
                }
                '\r' => {}
                ch => {
                    self.dessiner_caractere(self.cursor_x, self.cursor_y, ch);
                    self.cursor_x += CHAR_WIDTH;
                    if self.cursor_x >= self.width - 20 {
                        self.cursor_x = 20;
                        self.cursor_y += LINE_HEIGHT;
                        if self.cursor_y >= max_y {
                            self.scroll_up();
                        }
                    }
                }
            }
        }
    }

    pub fn effacer_dernier_caractere(&mut self) {
        if self.addr.is_null() { return; }
        if self.cursor_x > 20 {
            self.cursor_x -= CHAR_WIDTH;
            self.effacer_bloc(self.cursor_x, self.cursor_y, CHAR_WIDTH, CHAR_HEIGHT);
        }
    }

    fn scroll_up(&mut self) {
        if self.addr.is_null() { return; }
        let pitch = self.pitch;
        let start_y = 20;
        let max_y = self.max_y();

        unsafe {
            if max_y > start_y + LINE_HEIGHT {
                for y in start_y..(max_y - LINE_HEIGHT) {
                    for x in 0..self.width {
                        let src = *self.addr.add((y + LINE_HEIGHT) * pitch + x);
                        *self.addr.add(y * pitch + x) = src;
                    }
                }
                for y in (max_y - LINE_HEIGHT)..max_y {
                    for x in 0..self.width {
                        *self.addr.add(y * pitch + x) = 0x00_00_00_00;
                    }
                }
            }
        }
        self.cursor_y = max_y - LINE_HEIGHT;
    }

    fn effacer_bloc(&mut self, px: usize, py: usize, w: usize, h: usize) {
        unsafe {
            let pitch = self.pitch;
            let base = self.addr;
            for dy in 0..h {
                for dx in 0..w {
                    let x = px + dx;
                    let y = py + dy;
                    if x < self.width && y < self.height {
                        *base.add(y * pitch + x) = 0x00_00_00_00;
                    }
                }
            }
        }
    }

    fn dessiner_caractere(&mut self, px: usize, py: usize, c: char) {
        if self.addr.is_null() { return; }
        
        let max_y = self.max_y();
        if py >= max_y { return; }

        let code = (c as usize).min(FONT_8X16.len() - 1);
        let glyph = &FONT_8X16[code];
        let color = 0x00_00_FF_00; // Vert terminal vif

        unsafe {
            let pitch = self.pitch;
            let base = self.addr;

            for (row, &byte_row) in glyph.iter().enumerate() {
                for col in 0..8 {
                    let bit_on = (byte_row & (1 << (7 - col))) != 0;
                    
                    for dy in 0..FONT_SCALE {
                        for dx in 0..FONT_SCALE {
                            let x = px + (col * FONT_SCALE) + dx;
                            let y = py + (row * FONT_SCALE) + dy;
                            if x < self.width && y < max_y {
                                if bit_on {
                                    *base.add(y * pitch + x) = color;
                                } else {
                                    *base.add(y * pitch + x) = 0x00_00_00_00;
                                }
                            }
                        }
                    }
                }
            }
        }
    }

    pub fn nettoyer_ecran(&mut self) {
        if self.addr.is_null() { return; }
        unsafe {
            let total_pixels = self.pitch * self.height;
            for i in 0..total_pixels {
                *self.addr.add(i) = 0x00_00_00_00;
            }
            self.cursor_x = 20;
            self.cursor_y = 20;
        }
    }
}

impl fmt::Write for FramebufferConsole {
    fn write_str(&mut self, s: &str) -> fmt::Result {
        self.ecrire_chaine(s);
        Ok(())
    }
}

lazy_static! {
    pub static ref ECRIVAIN: Mutex<FramebufferConsole> = Mutex::new(FramebufferConsole::new());
    pub static ref TAMPON_CAPTURE: Mutex<Option<String>> = Mutex::new(None);
}

pub fn init_framebuffer(addr: *mut u32, width: usize, height: usize, pitch: usize) {
    ECRIVAIN.lock().init(addr, width, height, pitch);
}

/// Fonction utilitaire permettant aux modules externes (comme edt) d'accéder au framebuffer
pub fn avec_framebuffer<F>(f: F)
where
    F: FnOnce(*mut u32, usize, usize, usize),
{
    let ecrivain = ECRIVAIN.lock();
    if !ecrivain.addr.is_null() {
        f(ecrivain.addr, ecrivain.width, ecrivain.height, ecrivain.pitch);
    }
}

pub fn demarrer_capture() {
    *TAMPON_CAPTURE.lock() = Some(String::new());
}

pub fn arreter_capture() -> Option<String> {
    TAMPON_CAPTURE.lock().take()
}

pub fn clear_screen() {
    ECRIVAIN.lock().nettoyer_ecran();
}

pub fn effacer_dernier_caractere() {
    ECRIVAIN.lock().effacer_dernier_caractere();
}

// --- [MACROS : print et println] ---
#[macro_export]
macro_rules! print {
    ($($arg:tt)*) => {
        $crate::vga_buffer::_print(format_args!($($arg)*))
    };
}

#[macro_export]
macro_rules! println {
    () => {
        $crate::print!("\n")
    };
    ($($arg:tt)*) => {
        $crate::print!("{}\n", format_args!($($arg)*))
    };
}

#[doc(hidden)]
pub fn _print(args: fmt::Arguments) {
    use core::fmt::Write;
    use x86_64::instructions::interrupts;

    interrupts::without_interrupts(|| {
        let mut capture = TAMPON_CAPTURE.lock();
        if let Some(ref mut buffer_texte) = *capture {
            let _ = buffer_texte.write_fmt(args);
        } else {
            ECRIVAIN.lock().write_fmt(args).unwrap();
        }
    });
}
